#!/usr/bin/env node
/**
 * Writes `docs/frontend-cache.md`: what the web app caches, how fresh it stays, and what every
 * write refreshes. Generated from the source so it cannot drift. Run after changing the cache.
 *
 *   node scripts/cache-report.mjs
 */
import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const web = path.resolve(here, '../apps/web');
const out = path.resolve(here, '../docs/frontend-cache.md');

const skip = /(\.test\.|\.spec\.|[\\/]test[\\/]|node_modules|[\\/]\.next[\\/])/;
function walk(dir) {
  const found = [];
  for (const name of readdirSync(dir)) {
    const full = path.join(dir, name);
    if (skip.test(full)) continue;
    if (statSync(full).isDirectory()) found.push(...walk(full));
    else if (/\.(ts|tsx)$/.test(name)) found.push(full);
  }
  return found;
}
const rel = (file) => path.relative(web, file).split(path.sep).join('/');
const sources = ['app', 'components', 'features', 'hooks', 'lib', 'providers', 'stores']
  .flatMap((dir) => walk(path.join(web, dir)))
  .map((file) => ({ file: rel(file), text: readFileSync(file, 'utf8') }));

// 1. Query factories: `name: (args) => queryOptions({ queryKey: queryKeys.x.y(...) ... ...persistedQuery('tier') | liveQuery('tier')`
const factoryRows = [];
for (const { file, text } of sources.filter((s) => /features\/[^/]+\/queries\.ts$/.test(s.file))) {
  const domain = file.split('/')[1];
  const pattern = /^\s{2}(\w+): \([^)]*\) =>\s*(?:queryOptions|infiniteQueryOptions)\(\{([\s\S]*?)\n\s{4}\}\),?/gm;
  for (const match of text.matchAll(pattern)) {
    const body = match[2];
    const key = /queryKey:\s*([^\n]+?),?\n/.exec(body)?.[1]?.replace(/\s+/g, ' ') ?? '';
    const persisted = /persistedQuery\('(\w+)'\)/.exec(body);
    const live = /liveQuery\('(\w+)'\)/.exec(body);
    factoryRows.push({
      name: `${domain}.${match[1]}`,
      key: key.replace(/^queryKeys\./, '').replace(/,$/, ''),
      persist: persisted ? 'yes' : 'no',
      tier: (persisted ?? live)?.[1] ?? 'standard',
      file,
    });
  }
}

// 2. Mutations: migrated (declare affects) and legacy (bare useMutation).
const migrated = [];
const legacy = [];
for (const { file, text } of sources) {
  if (file === 'lib/query/mutations.ts') continue;
  for (const match of text.matchAll(/useApiMutation\(\{[\s\S]*?affects:\s*\[([^\]]*)\]/g)) {
    migrated.push({ file, affects: match[1].replace(/\s+/g, ' ').trim() || '(nothing cached)' });
  }
  if (/\buseMutation\(/.test(text)) {
    const roots = new Set();
    for (const match of text.matchAll(/queryKey:\s*(?:queryKeys\.(\w+)\.|\[\s*['"](\w+)['"])/g)) roots.add(match[1] ?? match[2]);
    const manual = /invalidateQueries|setQueryData|invalidateBlockRelatedQueries/.test(text);
    legacy.push({ file, roots: [...roots].join(', ') || '(not detected)', manual });
  }
}

// 3. Realtime events and domain relations from lib/query/domains.ts
const domains = readFileSync(path.join(web, 'lib/query/domains.ts'), 'utf8');
const events = [...domains.matchAll(/\['([\w.]+)', \[([^\]]*)\]\]/g)].map((m) => ({ prefix: m[1], domains: m[2].replace(/'/g, '') }));
const relations = [...domains.matchAll(/^\s{2}(\w+): \[([^\]]*)\],$/gm)]
  .filter((m) => /(auth|account|dashboard|errands|marketplace|offers|assignments|runner|notifications|conversations|billing|users|blocks|verification|security|consents|reference)/.test(m[1]))
  .map((m) => ({ domain: m[1], also: m[2].replace(/'/g, '') || '—' }));

const lines = [];
const table = (head, rows) => {
  lines.push(`| ${head.join(' | ')} |`, `| ${head.map(() => '---').join(' | ')} |`);
  for (const row of rows) lines.push(`| ${row.join(' | ')} |`);
  lines.push('');
};

lines.push('# Frontend cache', '', '> Generated by `node scripts/cache-report.mjs`. Do not edit by hand.', '');
lines.push('## Model', '',
  '- **The cache is for speed, never for truth.** A page paints what it has, then refetches whatever is older than its freshness tier.',
  '- **Persistence is opt-in** (`persistedQuery()` in `lib/query/persisted-query.ts`), scoped to one person and one app version, discarded on sign-out and on a user change, and never applied to the families in `NEVER_PERSIST` (`lib/query/policy.ts`).',
  '- **Writes declare what they change** with `useApiMutation({ affects })`. The same domain relations drive realtime events and other tabs (`lib/query/domains.ts`).',
  '- **Freshness comes from three paths:** refetch on mount, focus and reconnect when stale; realtime events while the live stream is up; polling only while it is not (`useLivePolling`).',
  '');

lines.push('## Queries in the factories', '');
table(['Factory', 'Key', 'Persisted', 'Freshness tier', 'File'],
  factoryRows.map((r) => [`\`${r.name}\``, `\`${r.key}\``, r.persist, r.tier, `\`${r.file}\``]));

lines.push('## Writes', '', '### Declared (`useApiMutation`)', '');
table(['File', 'Affects'], migrated.map((m) => [`\`${m.file}\``, `\`${m.affects}\``]));
lines.push('### Bare `useMutation` (guarded by `test/security/cache-discipline.test.ts`)', '');
if (legacy.length === 0) {
  lines.push('None. Every write declares what it affects, and the test fails on a new bare `useMutation`.', '');
} else {
  table(['File', 'Query roots it touches', 'Refreshes by hand'],
    legacy.map((m) => [`\`${m.file}\``, m.roots, m.manual ? 'yes' : '**no**']));
}

lines.push('## Realtime events', '');
table(['Event prefix', 'Domains refreshed (plus derived)'], events.map((e) => [`\`${e.prefix}\``, e.domains]));

lines.push('## Domain relations (one hop)', '');
table(['When this changes', 'These also refresh'], relations.map((r) => [`\`${r.domain}\``, r.also]));

lines.push('## Other tabs', '',
  'A write that declares `affects` posts the domain names on a `BroadcastChannel` (`lib/query/broadcast.ts`). Other tabs invalidate the same domains. Sign-out posts `clear`, and every tab drops its cache.', '');

mkdirSync(path.dirname(out), { recursive: true });
writeFileSync(out, lines.join('\n'));
console.log(`wrote ${path.relative(process.cwd(), out)} (${factoryRows.length} factories, ${migrated.length} declared writes, ${legacy.length} not migrated)`);
